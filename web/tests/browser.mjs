import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,readFile} from 'node:fs/promises';
const base=process.env.BASE_URL||'http://127.0.0.1:5173';
await mkdir('.qa',{recursive:true});
const browser=await chromium.launch({headless:true,args:JSON.parse(process.env.CHROMIUM_ARGS||'[]')});
const page=await browser.newPage({viewport:{width:1440,height:1120}});
page.setDefaultTimeout(60000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base,{waitUntil:'domcontentloaded',timeout:60000});
await page.getByText('369 measured runs',{exact:false}).waitFor();
assert.equal(await page.locator('tbody tr').count(),8);
await page.screenshot({path:'.qa/desktop.png',fullPage:true});
await page.getByRole('button',{name:'Throughput (tasks/s)',exact:false}).click();
assert.equal(await page.locator('th[aria-sort="ascending"]').innerText().then(t=>t.includes('Throughput')),true);
await page.getByRole('button',{name:'Throughput (tasks/s)',exact:false}).click();
assert.equal(await page.locator('th[aria-sort="descending"]').count(),1);
await page.getByRole('combobox',{name:'Metric',exact:true}).selectOption('p99_us');
assert.match(await page.locator('.chart-unit').innerText(),/p99/);
await page.getByRole('combobox',{name:'Workload',exact:true}).selectOption('burst');
assert.equal(await page.getByRole('combobox',{name:'Mode',exact:true}).inputValue(),'streaming');
await page.getByRole('combobox',{name:'Workload',exact:true}).selectOption('heavy');
await page.getByLabel('Search recorded runs').fill('v4');
assert.ok((await page.locator('tbody').innerText()).includes('Atomic stacks'));
assert.ok(!(await page.locator('tbody').innerText()).includes('Shared FIFO'));
await page.locator('.row-open').first().click();
await page.getByRole('dialog').waitFor();
await page.getByRole('button',{name:'Close run details'}).click();
await page.getByLabel('Search recorded runs').fill('');
await page.getByRole('button',{name:'Next page'}).click();
assert.match(await page.locator('.pagination').innerText(),/Page 2/);
const downloadPromise=page.waitForEvent('download');
await page.getByRole('button',{name:'Download CSV',exact:true}).click();
const download=await downloadPromise;assert.equal(download.suggestedFilename(),'threadpool-linux.csv');
await page.getByRole('button',{name:'Interactive menu',exact:true}).click();
assert.match(await page.locator('.configuration').innerText(),/Windows/);
await page.locator('input[type=file]').setInputFiles({name:'invalid.csv',mimeType:'text/csv',buffer:Buffer.from('a,b\n1,2')});
await page.getByRole('alert').waitFor();assert.match(await page.getByRole('alert').innerText(),/compatible/);
await page.getByRole('button',{name:'Dismiss error'}).click();
await page.locator('input[type=file]').setInputFiles({name:'my-results.csv',mimeType:'text/csv',buffer:await readFile('public/data/linux.csv')});
await page.getByText('CSV loaded in this browser.',{exact:false}).waitFor();
assert.equal(await page.getByRole('button',{name:'Uploaded CSV',exact:true}).getAttribute('aria-pressed'),'true');
await page.getByRole('button',{name:'Methodology',exact:true}).first().click();
await page.getByRole('heading',{name:'Behind the measurements.'}).waitFor();
await page.getByRole('button',{name:'Overview',exact:true}).click();
await page.getByRole('heading',{name:'More work. Less waiting.'}).waitFor();
await page.getByRole('button',{name:'Explorer',exact:true}).click();
await page.getByRole('button',{name:'Linux validation',exact:true}).click();
await page.getByRole('combobox',{name:'Metric',exact:true}).selectOption('throughput');
await page.reload({waitUntil:'domcontentloaded',timeout:60000});
await page.getByText('369 measured runs',{exact:false}).waitFor();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'.qa/mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'No whole-page horizontal overflow');
await page.setViewportSize({width:1440,height:1120});
await page.screenshot({path:'.qa/desktop.png',fullPage:true});
assert.deepEqual(errors,[]);
console.log('Browser checks passed: chart filters, streaming, search, details, pagination, downloads, invalid/valid uploads, navigation, desktop/mobile layout, no JS errors.');
await browser.close();
